#!/usr/bin/env bash
# Generates README.md in this directory: a two-column grid of all demo gifs,
# each gif linking to the example's main.go.
set -euo pipefail
cd "$(dirname "$0")"
demos=../site/static/demos

cell() {
  local name="$1"
  local img="![${name}](${demos}/${name}.gif)"
  if [ -f "${name}/main.go" ]; then
    printf '[%s](%s/main.go)' "${img}" "${name}"
  else
    printf '%s' "${img}"
  fi
}

names=()
while read -r f; do
  f="${f#./}"
  names+=("${f%.gif}")
done < <(cd "${demos}" && find . -name '*.gif' | LC_ALL=C sort)

{
  echo "# Examples"
  echo
  echo "Generated by \`index.sh\`; do not edit."
  echo
  echo "| | |"
  echo "|---|---|"
  for ((i = 0; i < ${#names[@]}; i += 2)); do
    left="$(cell "${names[i]}")"
    right=""
    if ((i + 1 < ${#names[@]})); then
      right="$(cell "${names[i + 1]}")"
    fi
    echo "| ${left} | ${right} |"
  done
} > README.md
